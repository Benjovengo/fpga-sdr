"""Single source of truth for the DDC: word widths, NCO tables and FIR coefficients.

`python -m model.design` regenerates rtl/ddc_params_pkg.vhd, so the RTL and the bit-accurate
model in ddc_model.py always use exactly the same numbers.
"""
from pathlib import Path

import numpy as np
from scipy import signal

ROOT = Path(__file__).resolve().parent.parent

# ------------------------------------------------------------------ word widths
IN_W = 16                    # input I/Q samples (ADC / RF transceiver)
PHASE_W = 32                 # NCO phase accumulator
LUT_AW = 10                  # NCO table address bits (1024 entries)
LUT_W = 16                   # NCO sin/cos amplitude
MIX_SHIFT = LUT_W - 1        # mixer product scaling (the table is Q1.15)
MIX_W = 18                   # mixer output, CIC input/output
CIC_N = 3                    # CIC stages
CIC_R = 8                    # CIC decimation (power of two)
CIC_GROWTH = CIC_N * (CIC_R.bit_length() - 1)   # N*log2(R) bits of gain
CIC_W = MIX_W + CIC_GROWTH   # CIC register width
FIR_TAPS = 31
COEF_W = 18
COEF_FRAC = 17               # coefficients are Q1.17
OUT_W = 18                   # DDC output

# ------------------------------------------------------------------ NCO tables
_k = np.arange(2 ** LUT_AW)
_amp = 2 ** (LUT_W - 1) - 1
SIN_LUT = [int(v) for v in np.round(_amp * np.sin(2 * np.pi * _k / 2 ** LUT_AW))]
COS_LUT = [int(v) for v in np.round(_amp * np.cos(2 * np.pi * _k / 2 ** LUT_AW))]


# ------------------------------------------------------------------ FIR design
def cic_response(f_out):
    """CIC magnitude at frequency f_out, in cycles per *output* sample (0..0.5)."""
    f_in = np.asarray(f_out, dtype=float) / CIC_R
    with np.errstate(invalid="ignore", divide="ignore"):
        h = np.sin(np.pi * f_in * CIC_R) / (CIC_R * np.sin(np.pi * f_in))
    return np.abs(np.where(f_in == 0, 1.0, h)) ** CIC_N


# Frequencies below are normalized to the output Nyquist rate (1.0 = fs_out / 2).
PASS_EDGE = 0.25
STOP_EDGE = 0.45


STOP_WEIGHT = 30            # least-squares weight of the stopband relative to the passband


def design_linear_phase():
    """Symmetric (linear-phase) channel filter that also flattens the CIC droop.

    Weighted least squares: the passband is split into short bands whose desired gain follows
    1/|H_cic|, so the CIC + FIR cascade is flat.
    """
    edges = np.linspace(0, PASS_EDGE, 9)
    bands, desired = [], []
    for lo, hi in zip(edges[:-1], edges[1:]):
        bands += [lo, hi]
        desired += [1.0 / cic_response(lo / 2), 1.0 / cic_response(hi / 2)]
    bands += [STOP_EDGE, 1.0]
    desired += [0.0, 0.0]
    weight = [1.0] * (len(edges) - 1) + [STOP_WEIGHT]
    return signal.firls(FIR_TAPS, bands, desired, weight=weight)


def design_minimum_phase(h_lin):
    """Minimum-phase filter with the same magnitude response as h_lin.

    h_lin convolved with itself has magnitude |H|^2 and is still linear-phase; the homomorphic
    method returns a minimum-phase filter whose magnitude is the square root of its input's,
    i.e. |H| again, with the same length as h_lin.
    """
    h_min = signal.minimum_phase(np.convolve(h_lin, h_lin), method="homomorphic")
    assert len(h_min) == FIR_TAPS, len(h_min)
    return h_min * (h_lin.sum() / h_min.sum())  # same DC gain


def quantize(h):
    q = [int(v) for v in np.round(np.asarray(h) * 2 ** COEF_FRAC)]
    lim = 2 ** (COEF_W - 1)
    assert all(-lim <= v < lim for v in q), "coefficient overflows COEF_W"
    return q


H_LINEAR = design_linear_phase()
H_MINPHASE = design_minimum_phase(H_LINEAR)
COEF_LINEAR = quantize(H_LINEAR)
COEF_MINPHASE = quantize(H_MINPHASE)
COEFS = {"linear": COEF_LINEAR, "minphase": COEF_MINPHASE}


# ------------------------------------------------------------------ VHDL package
def _vhdl_array(values, per_line=8):
    rows = [", ".join(f"{v:7d}" for v in values[i:i + per_line])
            for i in range(0, len(values), per_line)]
    return "(\n    " + ",\n    ".join(rows) + ")"


def write_vhdl_package(path=ROOT / "rtl" / "ddc_params_pkg.vhd"):
    consts = dict(IN_W=IN_W, PHASE_W=PHASE_W, LUT_AW=LUT_AW, LUT_W=LUT_W, MIX_SHIFT=MIX_SHIFT,
                  MIX_W=MIX_W, CIC_N=CIC_N, CIC_R=CIC_R, CIC_GROWTH=CIC_GROWTH, CIC_W=CIC_W,
                  FIR_TAPS=FIR_TAPS, COEF_W=COEF_W, COEF_FRAC=COEF_FRAC, OUT_W=OUT_W)
    body = "\n".join(f"  constant {k:<10} : natural := {v};" for k, v in consts.items())
    text = f"""-- Generated by model/design.py -- do not edit by hand.
-- Word widths, NCO tables and FIR coefficients shared by the RTL and the Python model.
package ddc_params_pkg is
{body}

  type lut_t is array (0 to 2**LUT_AW - 1) of integer;
  constant SIN_LUT : lut_t := {_vhdl_array(SIN_LUT)};
  constant COS_LUT : lut_t := {_vhdl_array(COS_LUT)};

  type coef_t is array (0 to FIR_TAPS - 1) of integer;
  -- Linear-phase channel filter with CIC droop compensation (group delay {(FIR_TAPS - 1) // 2} samples).
  constant COEF_LINEAR : coef_t := {_vhdl_array(COEF_LINEAR)};
  -- Minimum-phase filter with the same magnitude response (lower group delay).
  constant COEF_MINPHASE : coef_t := {_vhdl_array(COEF_MINPHASE)};
end package;
"""
    path.write_text(text)
    return path


if __name__ == "__main__":
    print(f"wrote {write_vhdl_package()}")
