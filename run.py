#!/usr/bin/env python3
"""Run all RTL tests with VUnit.

1. Regenerates rtl/ddc_params_pkg.vhd and the golden vectors from the Python model.
2. Simulates tb_ddc in four configurations (FIR structure x FIR phase), and the board-level
   testbench tb_de10nano.
3. Collects the measured latencies into doc/results.md.

Usage:  python run.py            (all tests; add -p 4 to run in parallel, -v for verbose)
        python run.py --list
"""
from pathlib import Path

from vunit import VUnit

from model import design
from model.ddc_model import write_vectors

ROOT = Path(__file__).resolve().parent
BUILD = ROOT / "build"
VEC_DIR = BUILD / "vectors"
RESULT_DIR = BUILD / "results"

CONFIGS = {
    # name                       (G_TRANSPOSED, G_MINPHASE)
    "tree_linear":               (False, False),   # baseline
    "tree_minphase":             (False, True),
    "transposed_linear":         (True, False),
    "transposed_minphase":       (True, True),     # low latency
}


def main():
    design.write_vhdl_package()
    write_vectors(VEC_DIR)
    RESULT_DIR.mkdir(parents=True, exist_ok=True)

    vu = VUnit.from_argv(compile_builtins=False)
    vu.add_vhdl_builtins()
    lib = vu.add_library("lib")
    lib.add_source_files(ROOT / "rtl" / "*.vhd")
    lib.add_source_files(ROOT / "boards" / "*" / "*.vhd")
    lib.add_source_files(ROOT / "tb" / "*.vhd")

    tb = lib.test_bench("tb_ddc")
    for name, (transposed, minphase) in CONFIGS.items():
        tb.add_config(name=name, generics=dict(
            G_TRANSPOSED=transposed, G_MINPHASE=minphase,
            G_VEC_DIR=VEC_DIR.as_posix(), G_RESULT_FILE=(RESULT_DIR / name).as_posix()))

    vu.main(post_run=lambda results: write_results_table())


def write_results_table():
    """doc/results.md from the latencies the testbench wrote (only for configurations that ran)."""
    rows = []
    for name in CONFIGS:
        f = RESULT_DIR / f"{name}_step.txt"
        if not f.exists():
            continue
        first, step50, r = (int(v) for v in f.read_text().split())
        rows.append((name, first, step50, r))
    if not rows:
        return
    base = next((s for n, _, s, _ in rows if n == "tree_linear"), None)
    lines = [
        "# Measured latency (RTL simulation)",
        "",
        "Generated by `run.py` from the `latency_step` test. Clock cycles at the input sample rate;",
        f"one output sample every {rows[0][3]} cycles (CIC decimation).",
        "",
        "| Configuration | First response (cycles) | 50 % of step (cycles) | vs. baseline |",
        "|---|---:|---:|---:|",
    ]
    for name, first, step50, _ in rows:
        gain = f"-{100 * (base - step50) / base:.0f} %" if base and name != "tree_linear" else "baseline"
        lines.append(f"| `{name}` | {first} | {step50} | {gain} |")
    out = ROOT / "doc" / "results.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"latency table written to {out}")


if __name__ == "__main__":
    main()
